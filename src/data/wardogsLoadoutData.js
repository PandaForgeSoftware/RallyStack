const ammoId = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

const buildAmmoFamily = ({
  calibre,
  stack,
  damage,
  speed,
  fmj,
  hp,
  ap,
}) => {
  const variants = [
    {
      label: 'Standard (FMJ)',
      code: 'FMJ',
      penetration: 1,
      ...fmj,
    },
    {
      label: 'Standard (FMJ) (T)',
      code: 'FMJ-T',
      penetration: 1,
      ...fmj,
      tracer: true,
    },
    {
      label: 'Flesh Damage (HP)',
      code: 'HP',
      penetration: 1.5,
      ...hp,
    },
    {
      label: 'Flesh Damage (HP) (T)',
      code: 'HP-T',
      penetration: 1.5,
      ...hp,
      tracer: true,
    },
    {
      label: 'Armor Piercing (AP)',
      code: 'AP',
      penetration: 0.3,
      ...ap,
    },
    {
      label: 'Armor Piercing (AP) (T)',
      code: 'AP-T',
      penetration: 0.3,
      ...ap,
      tracer: true,
    },
  ]

  return variants.map((variant) => ({
    id: ammoId(`${calibre}-${variant.code}`),
    name: `${calibre} ${variant.label}`,
    calibre,
    stack,
    damage,
    speed,
    penetration: variant.penetration,
    price: variant.price,
    unlockLevel: variant.level,
    unlockCost: variant.unlock,
    tracer: Boolean(variant.tracer),
    type: 'loose_ammo',
  }))
}

